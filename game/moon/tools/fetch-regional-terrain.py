"""Extract NASA LOLA data without downloading the 3.3 GB mosaic.
Requires Python, numpy, rasterio. Run with --out game/moon/data.
No interpolation across missing source pixels is permitted.
"""
import argparse, hashlib, json, math, os
from datetime import datetime, timezone
from pathlib import Path
os.environ.setdefault('GDAL_DISABLE_READDIR_ON_OPEN', 'EMPTY_DIR')
import numpy as np
import rasterio
from rasterio.windows import Window

SOURCE = 'https://pgda.gsfc.nasa.gov/data/LOLA_5mpp/87S/ldem_87s_5mpp.tif'
LAT, LON, R = -89.4624, -137.7808, 1737400.0

def project_local(x, z):
    # Great-circle destination: world +x east, +z south at the origin.
    p, l = math.radians(LAT), math.radians(LON)
    d = np.hypot(x, z) / R
    b = np.arctan2(x, -z)
    p2 = np.arcsin(np.sin(p)*np.cos(d) + np.cos(p)*np.sin(d)*np.cos(b))
    l2 = l + np.arctan2(np.sin(b)*np.sin(d)*np.cos(p), np.cos(d)-np.sin(p)*np.sin(p2))
    rho = 2*R*np.tan(np.pi/4 + p2/2)
    return rho*np.sin(l2), rho*np.cos(l2)

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args(); args.out.mkdir(parents=True, exist_ok=True)
    step, half = 5, 800
    axis = np.arange(-half, half+step, step); x,z = np.meshgrid(axis,axis)
    px,py = project_local(x,z)
    with rasterio.open('/vsicurl/'+SOURCE) as src:
        if src.transform.a != 5 or src.transform.e != -5 or src.scales != (1.0,):
            raise ValueError('Unexpected source encoding')
        # GeoTIFF transform describes pixel corners; sample at pixel centers.
        cols=(px-src.transform.c)/5-0.5; rows=(src.transform.f-py)/5-0.5
        c0,r0=int(np.floor(cols.min())),int(np.floor(rows.min()))
        w,h=int(np.floor(cols.max()))-c0+2,int(np.floor(rows.max()))-r0+2
        win=Window(c0,r0,w,h)
        a=src.read(1,window=win)
        if not np.isfinite(a).all(): raise ValueError('Missing/invalid source pixels; refusing to invent terrain')
        source_hash=hashlib.sha256(a.astype('<f4').tobytes()).hexdigest()
        cx=cols-c0; ry=rows-r0; ix=np.floor(cx).astype(int); iy=np.floor(ry).astype(int)
        u=cx-ix; v=ry-iy
        heights=a[iy,ix]*(1-u)*(1-v)+a[iy,ix+1]*u*(1-v)+a[iy+1,ix]*(1-u)*v+a[iy+1,ix+1]*u*v
        center=float(heights[len(axis)//2,len(axis)//2])
        q=np.rint((heights-center)*10).astype(np.int32)
        if q.min() < -32768 or q.max() > 32767: raise ValueError('Elevation overflow')
        raw=q.astype('<i2').tobytes()
        metadata=dict(source=SOURCE, product='https://pgda.gsfc.nasa.gov/products/81',
            citation='Barker et al. (2021), doi:10.1016/j.pss.2020.105119',
            retrieved=datetime.now(timezone.utc).isoformat(), lat=LAT,lon=LON,
            radiusMetres=R,width=len(axis),stepMetres=step,halfMetres=half,
            originHeightMetres=center,quantizationMetres=0.1,
            sourceWindow=dict(col=c0,row=r0,width=w,height=h),sourceWindowFloat32LEsha256=source_hash,
            heightsInt16LEsha256=hashlib.sha256(raw).hexdigest(),
            sourceCRS=src.crs.to_wkt(),sourceTransform=list(src.transform),
            sourceRangeMetres=[float(a.min()),float(a.max())],
            derivedRangeMetres=[float(heights.min()),float(heights.max())],
            method='5 m local east/south grid, spherical geodesic to source south-polar stereographic; bilinear interpolation at source pixel centers; relative decimetres. LOLA DEM includes interpolated cells, not an independent laser shot per grid cell.',
            limitations='5 m grid spacing is not 5 m resolving power or decimetre accuracy. No source count/error map included. Gameplay pad, crater field, ice/shadow and surface grain are synthetic overlays; not measured ice deposits or illumination.')
    (args.out/'regional-terrain.json').write_text(json.dumps(metadata,indent=2)+'\n')
    values=','.join(map(str,q.ravel()))
    (args.out/'regional-heights.js').write_text('// Generated by fetch-regional-terrain.py; NASA LOLA, Barker et al. (2021).\nexport const GRID = Object.freeze('+json.dumps({k:metadata[k] for k in ['width','stepMetres','halfMetres','originHeightMetres','lat','lon']})+');\nexport const DECIMETRES = new Int16Array(['+values+']);\n')
    print(json.dumps({k:metadata[k] for k in ['originHeightMetres','derivedRangeMetres','sourceWindow','heightsInt16LEsha256']},indent=2))

if __name__ == '__main__': main()
